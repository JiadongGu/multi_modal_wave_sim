"""Pierson-Moskowitz spectrum - the reference implementation.

This is the one spectrum written out in full, as the pattern for the others.
Read it before implementing JONSWAP or ECKV: the shape of the class, the
docstring conventions and the registration are all meant to be copied.

The physics
-----------
PM (1964) describes a *fully developed* sea: the wind has blown long enough
over enough distance that the waves have stopped growing, so the shape depends
on one parameter only. Written in terms of Hs and the peak frequency:

    S(omega) = (5/16) Hs^2 omega_p^4 omega^-5 exp(-(5/4) (omega_p/omega)^4)

The omega^-5 tail is the Phillips equilibrium range - the shape a saturated
sea settles into because steeper waves simply break. The exponential cuts off
the low-frequency side, because waves longer than the peak have no mechanism
to be generated by this wind.

The (5/16) Hs^2 omega_p^4 prefactor is already normalised: integrating this
gives m0 = Hs^2 / 16 exactly, so 4 sqrt(m0) returns the Hs you asked for.
`tools/selftest.py` asserts that, which is how you know a spectrum is right.
"""

from __future__ import annotations

import numpy as np

from ..registry import SPECTRA
from .base import WaveSpectrum


@SPECTRA.register("pierson_moskowitz")
class PiersonMoskowitz(WaveSpectrum):
    """Fully developed sea. One shape parameter: the peak frequency."""

    def energy(self, omega):
        omega = np.asarray(omega, dtype=float)
        wp = self.omega_p

        # omega = 0 would divide by zero. Mask it, compute, then write 0 back:
        # at zero frequency there is no energy, and a nan here would propagate
        # silently through the whole wave field.
        safe = np.where(omega > 0.0, omega, 1.0)

        s = (
            (5.0 / 16.0)
            * self.hs**2
            * wp**4
            * safe**-5.0
            * np.exp(-1.25 * (wp / safe) ** 4)
        )
        return np.where(omega > 0.0, s, 0.0)
